package app.solina.refuge.core.crypto

/**
 * چند خزانه — پیاده‌شده (فاز چندخزانه‌ای).
 *
 * هر خزانه یک هدر جدا (VaultHeader) با salt تصادفیِ خودش در پوشهٔ `vault-<id>` دارد؛
 * کلید خزانه (VK) هر خزانه جداگانه با رمز اصلی بسته می‌شود و salt متفاوت یعنی KEK
 * متفاوت — کلید یک خزانه هرگز ورودیِ خزانهٔ دیگر را باز نمی‌کند. هر خزانه ۲۴ کلمهٔ
 * بازیابی مخصوص خودش را دارد (اگر یک عبارت لو برود، فقط همان خزانه لو می‌رود).
 *
 * مهاجرت: خزانهٔ تک‌خزانه‌ایِ قدیمی بدون هیچ رمزگذاریِ دوباره، «خزانهٔ پیش‌فرض»
 * (`default`، «خزانهٔ اصلی») می‌شود؛ فایل‌هایش به `vault-default` می‌روند و همهٔ
 * ردیف‌های دیتابیس با مهاجرت ۲←۳ به همان خزانه نسبت داده می‌شوند.
 *
 * بکاپ: بکاپ RFGB v1 فقط خزانهٔ فعال را می‌گیرد و شناسه/نام خزانهٔ مبدأ را به‌عنوان
 * برچسب در JSON می‌نویسد؛ بکاپ‌های قدیمی (بدون برچسب) هنوز بازیابی می‌شوند.
 * همگام‌سازی فقط خزانهٔ فعال را همگام می‌کند؛ رکورد خزانهٔ دیگر با کلید این خزانه
 * باز نمی‌شود و رد می‌شود.
 */
object MultiVaultDesign {
    /** بازیابی جداگانه برای هر خزانه (۲۴ کلمهٔ مخصوص همان خزانه). */
    const val RECOVERY_PER_VAULT = true

    /** سقف پیشنهادی تعداد خزانه‌ها (برای اینکه UI و بکاپ قابل مدیریت بماند). */
    const val MAX_VAULTS = 5

    /** شناسهٔ خزانهٔ فعلی که بدون مهاجرت، «پیش‌فرض» می‌شود. */
    const val DEFAULT_VAULT_ID = "default"

    /** پیشوند info برای جداسازی دامنهٔ بسته‌بندی کلید هر خزانه (به VaultCrypto اضافه شود). */
    const val WRAP_INFO_PREFIX = "refuge/wrap/pw/v1/vault:"
}
